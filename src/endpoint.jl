# The endpoint macro, in all its glory

const ANAPHORIC_VAR = :self
const CONFIG_VAR = :config

const SUPPORTED_HTTP_METHODS = (:get, :post, :put, :patch, :delete, :head, :options)

"""
    @endpoint struct ... end
    @endpoint [func(...)] -> [struct ... end] -> [payload] -> url -> [resulttype]

Generate an endpoint implementation from a concise shorthand form.

This macro can be applied to either an endpoint struct definition or a chain of
_arrow forms_ joined by `->`. These arrow forms represent the flow of
information:
1. The creation of a request, from a function call (optional)
2. The `struct` used to represent the request data (optional, autogenerated from
   the function call)
3. Any payload provided with the request (if applicable)
4. The page URL the request is directed to (relative to the base URL)
5. The type that the response is expected to correspond to

For a basic API, this can be as simple as:

```julia
@endpoint israining(city::String) -> "checkrain/{city}" -> Bool
```

Using this macro is equivalent to implementing a plain struct, along with these
endpoint methods:
- [`urlpath`](@ref)
- [`parameters`](@ref) (if needed)
- [`payload`](@ref) (optionally)
- [`responsetype`](@ref)

In our `@endpoint israining() ...` example, in addition to defining the
`israining` function and an (implicit) `IsrainigEndpoint` struct, the macro will
generate the implementations `urlpath(rain::IsrainingEndpoint) = "checkrain/\$(rain.city)"` and
`responsetype(::IsrainingEndpoint) = Bool`.

In addition to applying `@endpoint` to a sequence of arrow forms you can also
apply it to a `struct` that starts with a special line of non-`struct` arrows.

For instance, our `israining()` example could be alternatively written as:

```julia
@endpoint struct IsrainingEndpoint
    israining(city) -> "checkrain/{city}" -> Bool
    city::String
end
```

This generates the exact same code as the initial example form.

For more information on how each component of the shorthand form is interpreted,
as well as more complex examples, see the extended help section.

See also: [`urlpath`](@ref), [`parameters`](@ref), [`payload`](@ref),
[`responsetype`](@ref), [`Request`](@ref), [`globalconfig`](@ref), [`@globalconfig`](@ref).

# Extended help

## Function forms

Should you chose to include a function call as the first arrow form, a function
definition with a matching signature will be generated. This requires
[`globalconfig(::Val{@__Module__})`](@ref globalconfig) to be defined, as is
done by [`@globalconfig`](@ref).

Without a `struct` form, the arguments of the function will be used to generate
a `struct` with a derived name (`\$(titlecase(funcname))Endpoint`), and populate
its fields.

With a `struct` form, all arguments that match a field name will inherit the
field's type and default value, though a positional argument followed by a
required one stays required. All the fields of the struct not present in the
signature will be added as keyword arguments, with `Union{..., Nothing}` typed
fields defaulting to `nothing`. This makes function forms an easy way to
prescribe positional, mandatory arguments with the flexibility to fully specify
the endpoint with keyword arguments.

A docstring on an `@endpoint` with a function form documents the function, and
the struct is given a docstring that points to it. Without a function form, the
docstring documents the struct.

```julia
\"\"\"
    dothing(input) -> Output

Do the thing to `input`.
\"\"\"
@endpoint dothing(input::Foo) -> "thing/{input}" -> Output
```

## Struct forms

The endpoint struct can be given explicitly, or generated from the function
call. For instance, the function call `api(target::String; count::Int=1)` will
generate this struct form:

```
@kwdef struct ApiEndpoint
    target::String
    count::Int = 1
end
```

When autogenerated, or not specified, the endpoint supertype is selected from
`AbstractEndpoint`, `SingleEndpoint`, `ListEndpoint`, and `StreamEndpoint` based
on the supertype of the output form (a `Stream` output selects `StreamEndpoint`;
see the streaming manual).

If `@endpoint` is directly applied to a `struct`, the first line of the struct
is removed and parsed as a series of arrow forms. That line is always taken as the
endpoint's, so a string there is its URL; a docstring for the first field goes
after it.

```
@endpoint ApiEndpoint
    api(target; count) -> ...
    target::String
    count::Int = 1
end
```

This makes no difference to the generated code, and is purely a matter of
personal preference (I prefer explicit structs for more complex forms).

## Payload forms

HTTP methods like `:post`, `:put`, and `:patch` include a content payload (also
referred to as the request body). The payload can be specified with a _payload
form_ that names a field of the endpoint struct, names a global variable, or is
an expression is evaluated to generate the payload value (with the current
endpoint available through the anaphoric variable `$ANAPHORIC_VAR`).

Unless otherwise specified, an endpoint that includes a payload is assumed to be
a `:post` request (`:get` without).

```
@endpoint upload(content::String) -> content -> "create" -> Status
```

This is equivalent to the explicit HTTP method form:

```
@endpoint upload(content::String) -> content -> :post("create") -> Status
```

In this example `content` is a `String`, and so a `:post` request is made to
`"\$BASEURL/create"` with `content` as the payload/body. More complex types are
encoded according with [`writepayload`](@ref) according to [`dataformat`](@ref).

## URL forms

The endpoint URL is represent by a string, relative to the base URL of the API
(a leading `/` is stripped). Such paths usually consist of a path component, and
optionally a query component.

```julia
"some/path/for/my/api?query=param&other=value"
```

Within this endpoint URL, you can include references to fields of the struct (or
global variables) by surrounding them with curly braces.

```julia
"page/{somefield}?param={another}&{globalvar}=7"
```

Parameters with a value of `nothing` are omitted from the query string, and a
component without a value (`?verbose`) is sent as written.

For convenience, a parameter by the same name as the field can be referred to by
the field name alone (e.g. `?{var}` instead of `?var={var}`).

In more complex cases, arbitrary Julia code can be included in the curly braces.
This code will be evaluated with the endpoint value bound the the anaphoric
variable `$ANAPHORIC_VAR` as well as `$CONFIG_VAR` for the request
configuration.

```julia
"page/{if self.new \\"new\\" else \\"fetch\\" end}/{id}"
```

If that's not enough, you can also use an arbitrary expression in place of the
endpoint string:

```julia
if self.create "pages/create/" else "pages/fetch/id/" * self.id end
```

When using expression instead of a string though, curly braces are not
interpreted as field references.

### Specifying the HTTP method

By default, it is guessed whether the API expects a `:get` or `:post` request
based on the presence or absence of an input form. This can be explicitly
specified by wrapping the URL form in an HTTP method symbol, for example:

```julia
:head("existence/{entity}")
```

## Response type forms

It is sensible to parse the raw response into a more informative Julia
representation. The response type specifies what type the response can be parsed
to, which is performed by [`interpretresponse`](@ref) according to
[`dataformat`](@ref).

Often the result type will name a struct defined with [`@jsondef`].

The result type may be omitted when the response body is of no interest, which
is equivalent to giving `Nothing`: the body is discarded, the response is never
cached, and the endpoint returns `nothing`.

```julia
@endpoint announce(msg::String) -> msg -> :post("events")
```

When the URL is an expression rather than a string (or `:method(url)` form), the
result type cannot be told apart from it, so must be given explicitly.

The parsed result can be reinterpreted into another form with
[`postprocess`](@ref). By default, [`ListResponse`](@ref)-type responses from a
[`ListEndpoint`](@ref) are restructured into a [`List`](@ref) to facilitate
paging.

# Examples

```julia
@endpoint struct ShuffleEndpoint <: SingleEndpoint
    "deck/{deck}/shuffle?remaining={ifelse(self.remaining, '1', '0')}" -> Deck
    deck::String
    remaining::Bool
end
```

This is equivalent to defining the struct by itself, and then separately
defining the three basic endpoint methods.

```julia
struct ShuffleEndpoint <: SingleEndpoint
    deck::String
    remaining::Bool
end

$(@__MODULE__).urlpath(shuf::ShuffleEndpoint) =
    "deck/\$(shuf.deck)/shuffle"
$(@__MODULE__).parameters(shuf::ShuffleEndpoint) =
    ["remaining" => string(shuf.remaining)]
$(@__MODULE__).responsetype(shuf::ShuffleEndpoint) = Deck
```
"""
macro endpoint(args...)
    einfo = extract_forms(args; mod=__module__)
    efields = Symbol[f.name for f in einfo.fields]
    body = Expr[]
    # Standard components: struct, page, parameters, responsetype
    structdef = Expr(:macrocall, GlobalRef(Base, Symbol("@kwdef")), __source__, einfo.structdef)
    if isnothing(einfo.func)
        push!(body, structdef)
    else
        # The docstring goes to the function (marked below), and the struct points to it
        push!(body, undocumented(macroexpand(__module__, structdef; recursive = false)))
        push!(body, Expr(:macrocall, GlobalRef(Core, Symbol("@doc")), __source__,
                         "    $(einfo.structname)\n\nThe request made by `$(first(einfo.func.args))`, which see.\n",
                         einfo.structname))
    end
    defform(func::Symbol, ::Nothing, body) =
        :($(@__MODULE__).$func($CONFIG_VAR::$RequestConfig, $ANAPHORIC_VAR::$(einfo.structname)) = $body)
    defform(func::Symbol, params::Vector{Symbol}, body) =
        :($(@__MODULE__).$func($CONFIG_VAR::$RequestConfig, $ANAPHORIC_VAR::$(einfo.structname){$(params...)}) where {$(params...)} = $body)
    varcontext = (; varname = ANAPHORIC_VAR, localvars = [ANAPHORIC_VAR, CONFIG_VAR], knownfields = efields, mod=__module__)
    if !isnothing(einfo.in)
        inval = varform(einfo.in; varcontext...)
        push!(body, :($(@__MODULE__).payload($CONFIG_VAR::$RequestConfig, $ANAPHORIC_VAR::$(einfo.structname)) = $inval))
    end
    path, params = if einfo.url isa String
        parse_endpoint_url(einfo.url; varcontext..., filename = string(__source__.file))
    else
        varform(einfo.url; varcontext...), nothing
    end
    push!(body, defform(:urlpath, einfo.structparams, path))
    if !isnothing(params)
        paramvec = Expr(:vect, params...)
        finalparam = :($(Vector{Pair{String, String}})(
            $filter($(!isnothing), $(Vector{Union{Pair{String, String}, Nothing}})(
                $paramvec))))
        push!(body, defform(:parameters, einfo.structparams, finalparam))
    end
    # `responsetype` takes a single endpoint argument (no `config`), so it
    # needs its own emission path, not the two-arg `defform`.
    rt_def = if isnothing(einfo.structparams)
        self = :($ANAPHORIC_VAR::$(einfo.structname))
        :($(@__MODULE__).responsetype($self) = $(einfo.out))
    else
        self = :($ANAPHORIC_VAR::$(einfo.structname){$(einfo.structparams...)})
        :($(@__MODULE__).responsetype($self) where {$(einfo.structparams...)} = $(einfo.out))
    end
    push!(body, rt_def)
    # Authentication (emit only the non-default methods, to avoid noise).
    authself(name) = if isnothing(einfo.structparams)
        :($(@__MODULE__).$name($ANAPHORIC_VAR::$(einfo.structname)))
    else
        :($(@__MODULE__).$name($ANAPHORIC_VAR::$(einfo.structname){$(einfo.structparams...)}) where {$(einfo.structparams...)})
    end
    scheme, policy = einfo.auth
    scheme isa NoAuth ||
        push!(body, :($(authself(:authscheme)) = $scheme))
    policy === :off && einfo.authmarker !== :noauth ||
        push!(body, :($(authself(:authpolicy)) = $(QuoteNode(policy))))
    # Function (optional)
    if !isnothing(einfo.func)
        fnoconfig, fconfig = generate_funcalls(einfo; mod=__module__)
        push!(body, Expr(:macrocall, GlobalRef(Base, Symbol("@__doc__")), __source__, fnoconfig), fconfig)
    end
    esc(Expr(:block, body...))
end

# `expr` with its `@__doc__` markers removed, so a docstring passes it by
undocumented(expr) =
    if Meta.isexpr(expr, :macrocall) && isdocmarker(expr.args[1])
        undocumented(last(expr.args))
    elseif expr isa Expr
        Expr(expr.head, map(undocumented, expr.args)...)
    else
        expr
    end

const AUTH_MARKERS = (:auth, :authoption, :noauth)

function resolve_auth(marker::Union{Symbol, Nothing}, mod::Module)
    scheme, policy = globalauthdefault(Val(mod))
    if marker === :noauth
        (NoAuth(), :off)
    elseif marker === :auth
        (scheme, :required)
    elseif marker === :authoption
        (scheme, :optional)
    else
        (scheme, policy)
    end
end

# Whether `f` names `@__doc__`, written as a GlobalRef or a `Base.@__doc__`-style reference
isdocmarker(f) =
    Symbol("@__doc__") === if f isa GlobalRef
        f.name
    elseif Meta.isexpr(f, :., 2) && f.args[2] isa QuoteNode
        f.args[2].value
    else
        f
    end

allowsnothing(type) =
    Meta.isexpr(type, :curly) && first(type.args) === :Union && :Nothing in type.args[2:end]

function generate_funcalls(einfo; mod::Module)
    includedargs = Symbol[]
    fspecs = Dict(f.name => (; type=f.type, default=f.default) for f in einfo.fields)
    fname = first(einfo.func.args)
    args, kwargs = if length(einfo.func.args) >= 2 && Meta.isexpr(einfo.func.args[2], :parameters)
        einfo.func.args[3:end], einfo.func.args[2].args
    else
        einfo.func.args[2:end], Expr[]
    end
    function argexpr(name::Symbol, type, default, iskeyword::Bool)
        iskeyword && isnothing(default) && allowsnothing(type) && (default = :nothing)
        arg = if isnothing(type) name else Expr(:(::), name, type) end
        if isnothing(default) arg else Expr(:kw, arg, default) end
    end
    function isrequired(arg)
        Meta.isexpr(arg, :kw) && return false
        name = if Meta.isexpr(arg, :(::), 2) first(arg.args) else arg end
        isnothing(get(fspecs, name, (; default = nothing)).default)
    end
    for (set, iskeyword) in ((args, false), (kwargs, true)), i in eachindex(set)
        arg = set[i]
        name, type, default = nothing, nothing, nothing
        if Meta.isexpr(arg, :kw, 2)
            arg, default = arg.args
        end
        if Meta.isexpr(arg, :(::), 2)
            name, type = arg.args
        elseif arg isa Symbol
            name = arg
        end
        name isa Symbol || throw(ArgumentError("Malformed function argument $(set[i]) in @endpoint function"))
        push!(includedargs, name)
        fspec = get(fspecs, name, nothing)
        isnothing(fspec) && throw(ArgumentError("Argument $name not found in @endpoint struct"))
        # An optional positional argument can't come before a required one
        inherited = if iskeyword || !any(isrequired, set[i+1:end]) fspec.default end
        set[i] = argexpr(name, something(type, fspec.type, Some(nothing)),
                         something(default, inherited, Some(nothing)), iskeyword)
    end
    for field in einfo.fields
        field.name ∈ includedargs || push!(kwargs, argexpr(field.name, field.type, field.default, true))
    end
    fcall = if isempty(kwargs)
        Expr(:call, fname, args...)
    else
        Expr(:call, fname, Expr(:parameters, kwargs...), args...)
    end
    if !isnothing(einfo.structparams)
        fcall = Expr(:where, fcall, einfo.structparams...)
    end
    estrucform = Expr(:call, einfo.structname, map(f -> f.name, einfo.fields)...)
    reqmethod = QuoteNode(einfo.method)
    perform_, Request_ = GlobalRef(@__MODULE__, :perform), GlobalRef(@__MODULE__, :Request)
    globalconfig_, Val_ = GlobalRef(@__MODULE__, :globalconfig), GlobalRef(Base, :Val)
    f1 = :($fcall = $perform_($Request_{$reqmethod}($globalconfig_($Val_{$mod}()), $estrucform)))
    confarg = gensym("request-config")
    pushfirst!(args, Expr(:(::), confarg, GlobalRef(@__MODULE__, :RequestConfig)))
    fcall = if isempty(kwargs)
        Expr(:call, fname, args...)
    else
        Expr(:call, fname, Expr(:parameters, kwargs...), args...)
    end
    if !isnothing(einfo.structparams)
        fcall = Expr(:where, fcall, einfo.structparams...)
    end
    f2 = :($fcall = $perform_($Request_{$reqmethod}($confarg, $estrucform)))
    f1, f2
end

function extract_forms(args::Tuple; mod::Module)
    marker, expr = if length(args) == 2 && first(args) isa QuoteNode
        first(args).value ∈ AUTH_MARKERS ||
            throw(ArgumentError("unknown @endpoint marker `:$(first(args).value)`; expected one of $AUTH_MARKERS"))
        first(args).value, last(args)
    elseif length(args) == 1
        nothing, only(args)
    else
        throw(ArgumentError("@endpoint expects an endpoint form, optionally preceded by an auth marker $AUTH_MARKERS"))
    end
    eauth = resolve_auth(marker, mod)
    efunc, esuper, estruct, estructname, estructparams, efields, ein, emethod, eurl, eout = ntuple(_ -> nothing, 10)
    components = if Meta.isexpr(expr, :struct)
        sinfo = decompose_struct(expr)
        !isnothing(sinfo.special) ||
            throw(ArgumentError("Expected special form with @endpoint, not a plain struct"))
        estruct = sinfo.desugar
        estructname = sinfo.name
        estructparams = sinfo.params
        efields = sinfo.fields
        esuper = sinfo.super
        linearize_arrowforms(sinfo.special)
    elseif Meta.isexpr(expr, :->, 2)
        linearize_arrowforms(expr)
    else
        throw(ArgumentError("@endpoint may be applied to either a struct or a series of -> forms, not a $(expr.head)"))
    end
    # 1: Check for `func(...) <: Type`
    if !isempty(components) && Meta.isexpr(first(components), :<:, 2)
        if !isnothing(estruct)
            throw(ArgumentError("When a struct is defined, the subtype must be declared by the struct form"))
        elseif !isnothing(esuper)
            throw(ArgumentError("Multiple subtype declarations in @endpoint"))
        end
        subject, esuper = popfirst!(components).args
        if Meta.isexpr(subject, :call)
            efunc = subject
        else
            throw(ArgumentError("Supertype declarations may be applied the function or stuct"))
        end
    end
    # 2: Check for `func(...)` (but not `:func(...)`, that's a HTTP method spec)
    if !isempty(components) && Meta.isexpr(first(components), :call) &&
        !(first(first(components).args) isa QuoteNode)
        efunc = popfirst!(components)
    end
    isnothing(efunc) || first(efunc.args) isa Symbol ||
        throw(ArgumentError("The @endpoint function must have a plain name, not `$(first(efunc.args))`"))
    # 3: Extract fields from function arguments
    if !isnothing(efunc) && isnothing(estruct)
        efields = @NamedTuple{name::Symbol, type::Any, default::Any}[]
        fargs = if length(efunc.args) <= 1
            Expr[]
        elseif Meta.isexpr(efunc.args[2], :parameters)
            vcat(efunc.args[3:end], efunc.args[2].args)
        else
            efunc.args[2:end]
        end
        for arg in fargs
            name, type, default = nothing, Any, nothing
            if Meta.isexpr(arg, :kw, 2)
                arg, default = arg.args
            end
            if arg isa Symbol
                name = arg
            elseif Meta.isexpr(arg, :(::), 2)
                name, type = arg.args
            else
                throw(ArgumentError("Malformed function argument $arg in @endpoint function"))
            end
            push!(efields, (name, type, default))
        end
    end
    isnothing(efields) && throw(ArgumentError("Unable to extract fields from @endpoint function"))
    # 4: Check for `struct`
    if isnothing(estruct) && !isempty(components) && Meta.isexpr(first(components), :struct)
        sinfo = decompose_struct(popfirst!(components); allowspecial = false)
        estruct = sinfo.desugar
        estructname = sinfo.name
        estructparams = sinfo.params
        efields = sinfo.fields
        (!isnothing(esuper) && !isnothing(sinfo.super)) &&
            throw(ArgumentError("Multiple subtype declarations in @endpoint"))
        if isnothing(sinfo.super) && !isnothing(esuper)
            estruct.args[2] = Expr(:<:, estruct.args[2], esuper)
        end
        esuper = something(sinfo.super, esuper, Some(nothing))
    end
    # Remaining components are `[in] -> url -> [out]`: a trailing component is the
    # result type unless it is URL-shaped, which tells `in -> url` from `url -> out`
    if isempty(components)
        throw(ArgumentError("Expected @endpoint to include at least a URL"))
    elseif length(components) > 3
        throw(ArgumentError("Too many components in @endpoint, at most could contain `func -> struct -> in -> url -> out`"))
    end
    urlshaped(form) = form isa String || (Meta.isexpr(form, :call, 2) && form.args[1] isa QuoteNode)
    has_out = !urlshaped(last(components))
    has_out && length(components) == 1 &&
        throw(ArgumentError("@endpoint needs a URL before the result type `$(only(components))`. \
                             If that is instead an expression URL, give the result type \
                             explicitly, e.g. `-> Nothing` to discard the response body."))
    !has_out && length(components) == 3 &&
        throw(ArgumentError("Too many components before the @endpoint URL `$(last(components))`: \
                             expected at most a payload, as in `[in] -> url -> [out]`"))
    ein, urlform, eout = if !has_out
        # `[url]` or `[in -> url]`; no result type.
        (length(components) == 2 ? first(components) : nothing), last(components), :Nothing
    elseif length(components) == 2
        nothing, components...
    else
        components
    end
    emethod, eurl = if Meta.isexpr(urlform, :call, 2) && urlform.args[1] isa QuoteNode
        urlform.args[1].value, urlform.args[2]
    else
        ifelse(isnothing(ein), :get, :post), urlform
    end
    emethod ∈ SUPPORTED_HTTP_METHODS || throw(ArgumentError("Unsupported HTTP method $emethod"))
    # Attempt to infer missing parameters
    if isnothing(esuper)
        outtype = try
            Core.eval(mod, eout)
        catch err
            throw(ArgumentError("@endpoint could not evaluate the result type `$eout`: \
                                 $(sprint(showerror, err)). If `$eout` is instead an \
                                 expression URL (after a payload), give the result type \
                                 explicitly, e.g. `-> Nothing` to discard the response body."))
        end
        outtype isa Type ||
            throw(ArgumentError("@endpoint result type `$eout` is not a type (it is a $(typeof(outtype)))"))
        esuper = GlobalRef(@__MODULE__, if outtype <: SingleResponse
            :SingleEndpoint
        elseif outtype <: ListResponse || outtype <: Vector
            :ListEndpoint
        elseif outtype <: Stream
            :StreamEndpoint
        else
            :AbstractEndpoint
        end)
        if !isnothing(estruct) && !isnothing(estructname)
            estruct.args[2] = Expr(:<:, estruct.args[2], esuper)
        end
    end
    if isnothing(estruct) && !isnothing(efunc)
        fieldlines = Any[]
        for (; name, type, default) in efields
            fline = name
            if !isnothing(type)
                fline = Expr(:(::), name, type)
            end
            if !isnothing(default)
                fline = Expr(:(=), fline, default)
            end
            push!(fieldlines, fline)
        end
        estructname = Symbol(titlecase(String(efunc.args[1])) * "Endpoint")
        estructparams = nothing
        estruct = Expr(:struct, false, Expr(:<:, estructname, esuper), Expr(:block, fieldlines...))
    end
    (; func=efunc, structdef=estruct, structname=estructname, structparams=estructparams,
     fields=efields, in=ein, method=emethod, url=eurl, out=eout, auth=eauth, authmarker=marker)
end

function decompose_struct(strux::Expr; allowspecial::Bool = true)
    Meta.isexpr(strux, :struct, 3) ||
        throw(ArgumentError("@endpoint expects a struct definition"))
    Meta.isexpr(strux.args[3], :block) ||
        throw(ArgumentError("@endpoint expects a block definition within the struct"))
    structmutable, structdecl, structdef::Expr = strux.args
    structlabel, structsuper = if Meta.isexpr(structdecl, :(<:), 2)
        structdecl.args
    elseif structdecl isa Symbol || Meta.isexpr(structdecl, :curly)
        structdecl, nothing
    else
        throw(ArgumentError("Struct name/supertype declaration is malformed"))
    end
    structname, structparams = if Meta.isexpr(structlabel, :curly)
        first(structlabel.args)::Symbol,
        [if Meta.isexpr(a, :(<:), 2) first(a.args) else a end::Symbol
             for a in structlabel.args[2:end]]
    else
        structlabel::Symbol, nothing
    end
    specialline, specialidx = nothing, 0
    fields = @NamedTuple{name::Symbol, type::Any, default::Any}[]
    for (i, line) in enumerate(structdef.args)
        if line isa LineNumberNode
            continue
        elseif allowspecial && isempty(fields) && isnothing(specialline) &&
            (Meta.isexpr(line, :(->), 2) || line isa String)
            specialline, specialidx = line, i
            continue
        elseif !allowspecial && Meta.isexpr(line, :(->), 2)
            throw(ArgumentError("Struct definition in @endpoint within a `->` chain must not contain a special line"))
        elseif line isa String # a field docstring, kept in the struct
            continue
        end
        type, default = :Any, nothing
        if Meta.isexpr(line, :(=), 2)
            line, default = line.args
        end
        if Meta.isexpr(line, :(::), 2)
            line, type = line.args
        end
        line isa Symbol ||
            throw(ArgumentError("Malformed field $(sprint(show, line)) in @endpoint struct"))
        name::Symbol = line
        push!(fields, (name, type, default))
    end
    desugar = if isnothing(specialline)
        strux
    else
        Expr(:struct, structmutable, structdecl, Expr(:block, deleteat!(copy(structdef.args), specialidx)...))
    end
    (; name=structname, super=structsuper, params=structparams, fields=fields, desugar, special=specialline)
end

"""
    linearize_arrowforms(expr::Expr) -> Vector{Any}

Linearize an expression of the form `a -> b -> c` into a vector of component
expressions.
"""
function linearize_arrowforms(expr::Expr)
    components = Any[]
    while Meta.isexpr(expr, :->, 2)
        push!(components, expr.args[1])
        expr = if Meta.isexpr(expr.args[2], :block, 2)
            expr.args[2].args[2]
        end
    end
    push!(components, expr)
    components
end

linearize_arrowforms(@nospecialize(x::Any)) = Any[x]

"""
    parse_endpoint_url(url::String; kwargs...)

Split an endpoint URL into its path and query components, and parse each using
`interp_curlies` (passing `kwargs`). A literal query component without a value
(`?flag`) is kept in the path, as a flag.
"""
function parse_endpoint_url(url::String; kwargs...)
    path, query = let parts = split_template(url, '?'; limit = 2)
        first(parts), if length(parts) == 2 last(parts) end
    end
    path = chopprefix(path, "/")
    isnothing(query) && return interp_curlies(String(path); ispath=true, kwargs...), nothing
    components = split_template(query, '&')
    parameters, flags = Expr[], String[]
    function mkparam(key, val)
        valvar = gensym("val")
        :(let $valvar = $val; if !isnothing($valvar); $string($key) => $string($valvar) end end)
    end
    for comp in components
        keyvalue = split_template(comp, '='; limit = 2)
        if length(keyvalue) == 2
            keyex, valex = interp_curlies(first(keyvalue); kwargs...), interp_curlies(last(keyvalue); kwargs...)
            push!(parameters, mkparam(keyex, valex))
        elseif startswith(comp, '{') && endswith(comp, '}')
            compparsed = Meta.parse(comp)
            Meta.isexpr(compparsed, :braces, 1) || throw(ArgumentError("Invalid query component $comp"))
            compvar = first(compparsed.args)
            compvar isa Symbol || throw(ArgumentError("Invalid query component $comp"))
            kwargs2 = ((; filename, k...) -> k)(; kwargs...)
            compex = varform(compvar; kwargs2...)
            push!(parameters, mkparam(String(compvar), compex))
        elseif !isempty(comp) && (flag = interp_curlies(comp; kwargs...)) isa String
            push!(flags, encode_uri_component(flag))
        else
            throw(ArgumentError("Invalid query component $comp"))
        end
    end
    pathex = interp_curlies(String(path); ispath=true, kwargs...)
    if !isempty(flags)
        pathex = Expr(:call, GlobalRef(Base, :string), pathex, "?" * join(flags, '&'))
    end
    pathex, parameters
end

# Split `str` at each `delim` that is neither escaped by `\` nor inside a `{…}` form
function split_template(str::String, delim::Char; limit::Int = 0)
    parts, start, idx = String[], firstindex(str), firstindex(str)
    while idx <= lastindex(str)
        char = str[idx]
        if char == '\\' && idx < lastindex(str)
            idx = nextind(str, nextind(str, idx))
        elseif char == '{'
            _, idx = Meta.parseatom(str, idx)
        elseif char == delim && (limit == 0 || length(parts) < limit - 1)
            push!(parts, str[start:prevind(str, idx)])
            start = idx = nextind(str, idx)
        else
            idx = nextind(str, idx)
        end
    end
    push!(parts, str[start:end])
end

"""
    interp_curlies(str::String; filename::String = "unknown", ispath::Bool = false, kwargs...)

Interpret `{curly}` expressions in `str` with `varform` (passing through `kwargs`).
A backslash makes the next character literal (e.g. `\\{`).

With `ispath`, interpolated values are percent-encoded and runs of `/` in the
literal text are collapsed. Otherwise (query text, which is encoded when sent),
percent-escapes in the literal text are decoded.
"""
function interp_curlies(str::String; filename::String = "unknown", ispath::Bool = false, kwargs...)
    components = Any[]
    literal = IOBuffer()
    function flushliteral()
        text = String(take!(literal))
        text = if ispath replace(text, r"/{2,}" => "/") else decode_uri_component(text) end
        isempty(text) || push!(components, text)
    end
    idx = firstindex(str)
    while idx <= lastindex(str)
        char = str[idx]
        if char == '\\' && idx < lastindex(str)
            idx = nextind(str, idx)
            print(literal, str[idx])
            idx = nextind(str, idx)
        elseif char == '{'
            flushliteral()
            expr, idx = Meta.parseatom(str, idx; filename)
            Meta.isexpr(expr, :braces, 1) ||
                throw(ArgumentError("Expected single {curly} form in URL, instead saw $expr"))
            exvar = varform(first(expr.args); kwargs...)
            push!(components, if ispath; :($encode_uri_component($string($exvar))) else exvar end)
        else
            print(literal, char)
            idx = nextind(str, idx)
        end
    end
    flushliteral()
    if isempty(components)
        ""
    elseif length(components) == 1
        first(components)
    else
        Expr(:call, GlobalRef(Base, :string), components...)
    end
end

"""
    varform(exval; varname::Symbol, knownfields::Vector{Symbol}, mod::Module)

Convert implicit references to a field of a variable `varname` into explicit references.

A field reference is recognised when `exval` is one of `knownfields`. If `exval` is a variable
but not a member of `knownfields` or a global variable, an `ArgumentError` is thrown.
"""
function varform(exval; varname::Symbol, localvars::Vector{Symbol}, knownfields::Vector{Symbol}, mod::Module)
    if exval isa Symbol
        if exval ∈ knownfields
            :($varname.$exval)
        elseif exval ∈ localvars
            exval
        elseif isdefined(mod, exval)
            exval
        else
            throw(ArgumentError("$exval is not a known field, local variable, or global variable"))
        end
    elseif Meta.isexpr(exval, :., 2)
        dotpath = Any[exval]
        while Meta.isexpr(dotpath[end], :., 2)
            elt = dotpath[end]
            dotpath[end] = elt.args[2]
            push!(dotpath, elt.args[1])
        end
        last(dotpath) isa Symbol || return exval
        if last(dotpath) ∈ knownfields
            dotpath[end] = QuoteNode(last(dotpath))
            foldl((d, x) -> Expr(:., d, x), reverse(dotpath), init=varname)
        elseif last(dotpath) ∈ localvars
            exval
        elseif isdefined(mod, last(dotpath))
            exval
        else
            throw(ArgumentError("$exval is not a known field, local variable, or global variable"))
        end
    else
        exval
    end
end
